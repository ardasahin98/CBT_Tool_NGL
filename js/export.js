// NGL lab test viewer layout (see NGL_DirectSimpleShearTest_DSSS_ID_*.csv)
const NGL_BLOCKS = [
  ["LAB", "labs", ["LAB_ID", "USER_ID", "LAB_NAME", "LAB_LAT", "LAB_LON", "LAB_DESC"]],
  ["LAB_PROGRAM", "progs", ["LAB_PROGRAM_ID", "LAB_PROGRAM_DESC"]],
  ["CITATION", "cits", ["CITATION_ID", "CITATION_TEXT", "CITATION_URL"]],
  ["SPECIMEN", "spec", ["SPEC_ID", "SPEC_REF", "SPEC_TOP", "SPEC_BASE", "SPEC_CREW", "SPEC_REM"]],
  ["SAMPLES", "samp", ["SAMP_ID", "SAMP_NAME", "SAMP_TYPE", "SAMP_TOP", "SAMP_BASE", "SAMP_SDIA", "SAMP_DATE", "SAMP_REC", "SAMP_DESC", "SAMP_REM"]],
  ["PLAS", "plas", ["PLAS_ID", "PLAS_LL", "PLAS_PL", "PLAS_METH", "PLAS_REM"]],
  ["DSSG", "dssg", ["DSSG_ID", "DSSG_E0", "DSSG_W0", "DSSG_DIAM", "DSSG_H0", "DSSG_DESC"]],
];
const TEXT_FIELD = /_(REF|NAME|DESC|REM|TEXT|URL|METH|CREW|TYPE|DATE)$/;
function nglVal(k, v) {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  const s = String(v);
  if (!TEXT_FIELD.test(k) && /^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(s.trim())) return s.trim();
  return `"${s.replace(/"/g, '""').replace(/[\r\n]+/g, " ")}"`;
}
const bitTxt = (v) => {
  if (v === true || v === false) return String(v);
  if (typeof v === "string" && v.length === 1 && v.charCodeAt(0) < 32) v = v.charCodeAt(0);
  const n = numOrNull(typeof v === "string" ? (v.match(/-?\d+/) || [])[0] : v);
  return n === null ? (v === null || v === undefined ? "null" : String(v)) : String(n !== 0);
};
// data rows of the CSV the tool computed from (# lines and the header removed)
function dataRows(t) {
  const lines = t.text.split(/\r?\n/).filter(l => l.trim() && !l.trimStart().startsWith("#"));
  return lines.slice(1);
}
function rawCSV(t) {
  const m = t.meta || {};
  if (!isNGL(t)) {
    const lines = [
      `Uploaded by user: ${t.name}`,
      `Exported from the CBT Tool v${TOOL_VERSION} On ${new Date().toString()}`,
      `Units: time ${t.units.time}, stress ${t.units.stress}, shear strain ${strainTxt(t.units.strain)}`,
      "",
      "Test Data",
      t.text.replace(/\s+$/, ""),
    ];
    return lines.join("\r\n");
  }
  const L = [
    "Downloaded from https://www.nextgenerationliquefaction.org (NGL REST API, via the CBT Tool)",
    `Downloaded By ${m.user || ""}`,
    `Downloaded On ${m.on || ""}`,
    "",
  ];
  for (const [title, key, cols] of NGL_BLOCKS) {
    let recs = m[key];
    recs = Array.isArray(recs) ? recs : (recs && Object.keys(recs).length ? [recs] : []);
    if (!recs.length) recs = [{}];
    L.push(title, cols.map(c => `"${c}"`).join(","));
    recs.forEach(r => L.push(cols.map(c => nglVal(c, r[c])).join(",")));
    L.push("");
  }
  const s = m.dsss || {};
  L.push("DSSS Metadata", "DSSS_ID, DSSG_ID, DSSS_ST, DSSS_TY, DSSS_DR, DSSS_DESC",
    [s.DSSS_ID, s.DSSG_ID, s.DSSS_ST, s.DSSS_TY].map(v => (v === null || v === undefined ? "null" : String(v)))
      .concat(bitTxt(s.DSSS_DR), String(s.DSSS_DESC ?? "").replace(/[\r\n,]+/g, " ")).join(","),
    "", "DSSS Data", "DSSS_TIME, DSSS_TAU, DSSS_SIGV, DSSS_YHV, DSSS_EPSV");
  dataRows(t).forEach(r => L.push(r.split(",").map(x => x.trim()).join(", ")));
  return L.join("\r\n");
}
const rawName = (t) => (isNGL(t) && t.meta.dsss ? `NGL_DirectSimpleShearTest_DSSS_ID_${t.meta.dsss.DSSS_ID}.csv` : baseName(t) + "_raw.csv");

