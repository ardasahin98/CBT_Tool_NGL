const csvVal = (v) => (v === null || v === undefined || (typeof v === "number" && !isFinite(v))) ? "" : (typeof v === "number" ? +v.toPrecision(8) : `"${String(v).replace(/"/g, '""')}"`);
const activeList = () => state.analysts.filter(a => state.active.has(a));
const strainTxt = (s) => (s === "dec" ? "decimal" : "%");
const numOrNull = (v) => (v === null || v === undefined || v === "" || !isFinite(+v) ? null : +v);
const isNGL = (t) => t.meta && t.meta.source === "NGL";
function refLine(t) {
  const m = t.meta || {};
  if (!isNGL(t)) return `# Source: uploaded file "${t.name}"`;
  return "# Source: NGL database | " + [
    `DSSS_ID ${m.dsss && m.dsss.DSSS_ID}`, `DSSG_ID ${m.dssg && m.dssg.DSSG_ID}`, `stage ${m.stage}`,
    `lab ${m.lab}`, `lab program ${m.prog}`, `sample ${m.sampName}`, `specimen ${m.specName}`,
    `e0 ${m.e0}`, `w0 ${m.w0}`, `LL ${m.ll}`, `PL ${m.pl}`, `downloaded by ${m.user} on ${m.on}`,
  ].join(" | ").replace(/[\r\n]+/g, " ");
}

